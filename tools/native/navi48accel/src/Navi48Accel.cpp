// the generic virtual hook (Navi48MetalOps.h vhook): returns true when the bring-up kext handled the slot (*r = its return value)
static bool n48_vhook(uint32_t cls, uint32_t slot, void *self, const uint64_t *a, uint32_t n, uint64_t *r) {
	if (!gOps || !gCtx || !gOps->vhook || !cap_has(gOps, N48_CAP_VHOOK)) return false;
	return gOps->vhook(gCtx, cls, slot, self, a, n, r) == 1;
}
// aux 0.0.3: the display-pipe hook (ABI 2 disp_hook), asked by the Navi48DisplayPipe trampolines. Display OFF (disp_enabled false: an ABI-1 table, flag clear, no
// hook) or no device = "not handled", so every pipe slot runs the FAMILY's own implementation, exactly as the family's own pipe object would.
static bool n48_disp_vhook(uint32_t cls, uint32_t slot, void *self, const uint64_t *a, uint32_t n, uint64_t *r) {
	if (!gCtx || !disp_enabled(gOps)) return false;
	return gOps->disp_hook(gCtx, cls, slot, self, a, n, r) == 1;
}

