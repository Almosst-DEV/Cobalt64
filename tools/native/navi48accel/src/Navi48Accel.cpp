// ---- Navi48Task -------------------------------------------------------------------------------------------------------------------------------
// AppleParavirtTask::init (0x142b85b6): IORangeAllocator::init(size-1, 0x1000, 0x400, 0), allocateRange(0, 0x1000) (page 0 reserved), then
// IOAccelTask::init(accel, 1, &ra) and a release of whatever the callee left in ra.
bool Navi48Task::setup(IOGraphicsAccelerator2 *accel, uint32_t kind) {
	N48_AUX_ENTER(false);
	uint64_t size = 0, reserve = 0;
	if (!gOps || !gCtx || gOps->task_window(gCtx, kind, &size, &reserve) != 0 || !task_window_ok(size, reserve)) return false;
	IORangeAllocator *ra = IORangeAllocator::withRange((IORangeScalar)(size - 1), kPage, 0x400u, 0);
	if (!ra) return false;
	if (reserve && !ra->allocateRange(0, (IORangeScalar)reserve)) { ra->release(); return false; }
	const bool ok = n48_IOAccelTask_init(this, accel, 1u, &ra);
	if (ra) ra->release();
	n48_trace(N48_TR_TASK, kind, ok);
	return ok;
}

// ---- Navi48DisplayMachine ---------------------------------------------------------------------------------------------------------------------
// aux 0.0.3 (M11H section 3.2 option C). IOGraphicsAccelerator2::requestProbe(1) calls this with accel+0x368, the provider cast at start, which for us is the
// Navi48MetalNub. The family's framebuffer discovery walk only looks at the children and clients of that argument (getChildIterator /
// copyClientWithCategory("IOFramebuffer") / getClientIterator, M11H section 3.2 and 11h.1 F4), and the nub has no framebuffer below it: RDNA4FB is attached to
// the GPU's IOPCIDevice, a sibling of the bring-up kext. So with display on and a nub argument, the walk starts at the PCI device the bring-up kext hands us
// (ops pci_device); every other case passes the family's own argument through (0.0.2). The walk makes IOService virtual calls only (no PCI config access).
N48_R_IOAccelDisplayMachine_267 Navi48DisplayMachine::start(IOPCIDevice *provider) {
	N48_AUX_ENTER(IOAccelDisplayMachine::start(provider));
	const bool on = disp_enabled(gOps);
	void *pci = (on && gCtx && gOps->pci_device) ? gOps->pci_device(gCtx) : nullptr;
	void *use = dm_walk_provider(on, n48_provider_is_nub((IOService *)(void *)provider), (void *)provider, pci);
	n48_trace(N48_TR_DM_START, (uint64_t)(uintptr_t)use, use != (void *)provider ? 1u : 0u);
	return IOAccelDisplayMachine::start((IOPCIDevice *)use);
}
