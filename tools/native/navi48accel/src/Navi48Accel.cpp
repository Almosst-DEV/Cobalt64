static const char kFallbackName[] = "n48accel";   // a static NON-NULL name: IOAccelDevice2::get_name strncpy's cfg->name (a NULL name would fault)

void Navi48Accelerator::populateAccelConfig(IOAccelConfig *cfg) {
	N48_AUX_ENTER_V();
	uint8_t *c = (uint8_t *)cfg;
	const int rc = (gOps && cfg) ? gOps->populate_config(c, 0x90u) : -1;
	n48_trace(N48_TR_POPULATE, (uint64_t)(int64_t)rc);
	if (!config_keep(gOps != nullptr, rc) && c) {
		// Fail closed WITHOUT a NULL name (validateConfigStructure is never called in start): keep the family defaults (non-zero IOSurface limits), a static name, and
		// tear the device down so the event machine's init finds no stamp VA and fails, which aborts the family's start.
		const uint64_t np = (uint64_t)(uintptr_t)kFallbackName;
		for (int i = 0; i < 8; ++i) c[i] = (uint8_t)(np >> (8 * i));
		if (ctx && gOps) { gOps->device_close(ctx); }
		if (gCtx == ctx) gCtx = nullptr;
		ctx = nullptr; stampMD = nullptr; stampVA = nullptr;
	}
}

