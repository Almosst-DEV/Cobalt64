static bool n48_aux_on() {
	uint32_t v = 0;
	const bool present = PE_parse_boot_argn("navi48-aux", &v, sizeof(v));
	return aux_enabled(present, v);
}
#define N48_AUX_ENTER(ret) do { if (!n48_aux_on()) return ret; } while (0)
