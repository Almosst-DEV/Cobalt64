#!/usr/bin/env python3
"""Decode every vtable in IOAcceleratorFamily2 + AppleParavirtGPU (and their base chain
IOAccelerator / IOService / IORegistryEntry / OSObject / OSMetaClassBase out of the
System/Boot KCs) into vtables/<Class>.tsv, generated/model.json and summary.md.

Inputs (read only): $C64_WORK/kexts/{com.apple.iokit.IOAcceleratorFamily2,
com.apple.driver.AppleParavirtGPU}, $C64_WORK/kc/{System,Boot}KernelExtensions.kc (see kcmod.py).
Outputs: $C64_LAYOUT_OUT/{vtables/*.tsv, model.json, paravirt_overrides.tsv, summary.md}. Apple-derived: do not publish.
Slot N of a vtable sits at <vtable symbol> + 16 + 8*N; the 64-bit value is a chained
fixup (see kcmod.py): target = raw & 0x3FFFFFFF, cache level = bits 30-31.
Usage: C64_WORK=... dump_vtables.py
"""
import json, os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import model as M
from kcmod import OUT

SIG_RE = re.compile(r'^(?P<cls>[A-Za-z_][\w]*)::(?P<name>~?[A-Za-z_]\w*)\((?P<args>.*)\)(?P<cv> const)?$')


def sig_of(demangled):
    m = SIG_RE.match(demangled)
    return m.groupdict() if m else None


def descendants(model, cls):
    """Classes (paravirt first, then family) whose chain contains cls, deterministic order."""
    out = [c for c, v in model['classes'].items() if cls in v['chain'][1:]]
    out.sort(key=lambda c: (model['classes'][c]['image'] != 'AppleParavirtGPU', len(model['classes'][c]['chain']), c))
    return out


def slot_signature(model, cls, i):
    """Best real signature for slot i of cls (whoever first implements it below), or None."""
    row = model['classes'][cls]['rows'][i]
    if not row['pure'] and not row['name'].startswith('<'):
        s = sig_of(row['name'])
        if s and s['cls'] == cls or (s and s['cls'] in model['classes'][cls]['chain']):
            return dict(s, source=cls)
    for d in descendants(model, cls):
        r = model['classes'][d]['rows']
        if i < len(r) and not r[i]['pure'] and not r[i]['name'].startswith('<'):
            s = sig_of(r[i]['name'])
            if s and s['cls'] in model['classes'][d]['chain']:
                return dict(s, source=d)
    return None


def write_tsv(model):
    for c, v in model['classes'].items():
        with open(os.path.join(OUT, 'vtables', c + '.tsv'), 'w') as f:
            f.write('# %s image=%s vtable=%s nslots=%d (+%d terminator) size=%s super=%s chain=%s\n' % (
                c, v['image'], v['vt_sym'], v['nslots'], v['nterm'], hex(v['size']) if v['size'] else '?', v['super'],
                '>'.join(v['chain'])))
            f.write('# columns: idx\tbyte_off(from vtable symbol)\ttarget(lvl:va)\tpure\tintroduced_by\tkind\tdemangled\tmangled\taliases\n')
            for r in v['rows']:
                tgt = '-' if r['lvl'] is None else '%d:0x%x' % (r['lvl'], r['va'])
                f.write('\t'.join([str(r['i']), '0x%x' % r['off'], tgt, 'PURE' if r['pure'] else '',
                                   r['intro'], r['kind'], r['name'], ','.join(r['mangled']),
                                   ' | '.join(r['aliases'])]) + '\n')


def write_paravirt(model):
    """generated/paravirt_overrides.tsv: every slot an AppleParavirtGPU class overrides vs its parent."""
    C = model['classes']
    with open(os.path.join(OUT, 'paravirt_overrides.tsv'), 'w') as f:
        f.write('paravirt_class\tparent\tslot\tbyte_off\tintroduced_by\tdemangled\n')
        for c in sorted(C):
            v = C[c]
            if v['image'] != 'AppleParavirtGPU':
                continue
            for r in v['rows']:
                if r['kind'] in ('override', 'new'):
                    f.write('%s\t%s\t%d\t0x%x\t%s\t%s\n' % (c, v['super'], r['i'], r['off'], r['intro'], r['name']))


def write_summary(model):
    C = model['classes']
    L = []
    w = L.append
    w('# IOAcceleratorFamily2 vtable / layout reconstruction (generated by dump_vtables.py; do not edit)\n')
    w('Sources: the family + paravirt kexts and the Boot/System KCs named in kcmod.py.')
    w('Slot N at vtable symbol + 16 + 8*N; chained-fixup target = raw & 0x3FFFFFFF (cache level bits 30-31).')
    w('`kind`: new = slot beyond the parent vtable, override = target differs from parent slot, inherit = same target.\n')
    w('\n## All classes\n')
    w('| class | image | slots | size | super | new | overrides | inherited | pure |')
    w('|---|---|---|---|---|---|---|---|---|')
    for c in sorted(C):
        v = C[c]
        k = {'new': 0, 'override': 0, 'inherit': 0}
        for r in v['rows']:
            k[r['kind']] += 1
        w('| %s | %s | %d | %s | %s | %d | %d | %d | %d |' % (
            c, v['image'], v['nslots'], hex(v['size']) if v['size'] else '?', v['super'] or '-',
            k['new'], k['override'], k['inherit'], sum(r['pure'] for r in v['rows'])))
    w('\n## Pure virtuals\n')
    w('Signatures come from the first paravirt (else family) descendant that implements the slot; '
      'C++ mangling omits return types, so RETURN TYPES ARE UNKNOWN.\n')
    for c in sorted(C):
        pures = [r for r in C[c]['rows'] if r['pure']]
        if not pures:
            continue
        w('### %s (%d pure of %d slots)\n' % (c, len(pures), C[c]['nslots']))
        w('| slot | byte off | signature (from) |')
        w('|---|---|---|')
        for r in pures:
            s = slot_signature(model, c, r['i'])
            txt = ('`%s(%s)%s` (%s)' % (s['name'], s['args'], s['cv'] or '', s['source'])) if s else 'no implementing descendant found'
            w('| %d | 0x%x | %s |' % (r['i'], r['off'], txt))
        w('')
    open(os.path.join(OUT, 'summary.md'), 'w').write('\n'.join(L) + '\n')


def main():
    m = M.build()
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(os.path.join(OUT, 'vtables'), exist_ok=True)
    json.dump(m, open(os.path.join(OUT, 'model.json'), 'w'), indent=0, sort_keys=True)
    write_tsv(m)
    write_summary(m)
    write_paravirt(m)
    print('classes:', len(m['classes']), '->', OUT)


if __name__ == '__main__':
    main()
