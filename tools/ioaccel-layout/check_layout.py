#!/usr/bin/env python3
"""Mechanical guard: does a -fapple-kext subclass of our reconstructed declarations emit a vtable
that has the KC's slot count and the KC's slot order?

For every class in $C64_LAYOUT_OUT/IOAccelFamily2_decl.h it builds a minimal subclass N48T_<Class> that
overrides exactly the slots the KC vtable of <Class> has as __cxa_pure_virtual, compiles it (x86_64,
-fapple-kext, the usual kext flags), reads OUR vtable out of the object file, and compares:
  * slot count (our vtable minus the zero terminator) == KC slot count;
  * the slots we DEFINE == the KC's pure slots (+ the dtor/getMetaClass overrides every OSDefine class adds);
  * every other slot is a reference to the right inherited method: SDK-range slots to the kernel's own
    method (name from the kernel vtable of IOService/IOUserClient/OSObject), family slots to the
    declared name (real signature or _vslotN with N == the slot index).
Prints MATCH (exit 0) or the first mismatch (exit 1). Deterministic; no PC, no loading.
Usage: check_layout.py [--regen] [--only Class,Class] [--keep]
"""
import json, os, re, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import objvt
import exports
from kcmod import demangle, OUT

MKSDK = os.environ.get('C64_MKSDK')   # path of a MacKernelSDK checkout (needs Headers/)
if not MKSDK:
    sys.exit('set C64_MKSDK to a MacKernelSDK checkout')
SDK_BASES = ('IOService', 'IOUserClient', 'OSObject')
BUILD = os.path.join(OUT, 'build')


def san(c):
    return re.sub(r'\W', '_', c)


def ensure(regen):
    g = OUT
    need = [os.path.join(g, x) for x in ('model.json', 'slots.json', 'IOAccelFamily2_decl.h')]
    if regen or not all(os.path.exists(x) for x in need):
        subprocess.run([sys.executable, os.path.join(here, 'dump_vtables.py')], check=True, stdout=subprocess.DEVNULL)
        subprocess.run([sys.executable, os.path.join(here, 'gen_header.py')], check=True, stdout=subprocess.DEVNULL)
    return json.load(open(os.path.join(g, 'model.json'))), json.load(open(os.path.join(g, 'slots.json')))


def visible_decl(slots, c, i):
    """Latest declaration of slot i visible in class c (walk up the emitted chain)."""
    while c in slots['classes']:
        e = slots['classes'][c]['slots'].get(str(i))
        if e:
            return c, e
        c = slots['classes'][c]['super']
    return None, None


def gen_tu(model, slots, classes):
    C = model['classes']
    L = ['// generated by check_layout.py', '#include "%s/IOAccelFamily2_decl.h"' % OUT]
    for c in classes:
        L.append('class N48T_%s : public %s {' % (c, c))
        L.append('    OSDeclareDefaultStructors(N48T_%s)' % c)
        L.append('public:')
        for r in C[c]['rows']:
            if not r['pure']:
                continue
            owner, e = visible_decl(slots, c, r['i'])
            assert e, (c, r['i'])
            if e['kind'] == 'real':
                L.append('    virtual N48_R_%s_%d %s(%s)%s override { return 0; }' % (san(e['owner']), r['i'], e['name'], e['args'], e['cv']))
            else:
                L.append('    virtual void _vslot%d() override {}' % r['i'])
        L.append('};')
        L.append('OSDefineMetaClassAndStructors(N48T_%s, %s)' % (c, c))
        L.append('static_assert(sizeof(N48T_%s) == N48_%s_SIZE, "derived size");' % (c, san(c)))
    return '\n'.join(L) + '\n'


def compile_tu(src, obj):
    sdk = subprocess.run(['xcrun', '--sdk', 'macosx', '--show-sdk-path'], capture_output=True, text=True).stdout.strip()
    cmd = ['clang++', '-arch', 'x86_64', '-target', 'x86_64-apple-macos11.0', '-isysroot', sdk, '-I%s/Headers' % MKSDK,
           '-mmacosx-version-min=11.0', '-DKERNEL', '-DKERNEL_PRIVATE', '-DDRIVER_PRIVATE', '-DAPPLE', '-DNeXT',
           '-D_FORTIFY_SOURCE=0', '-nostdinc', '-fno-builtin', '-fno-common', '-fno-stack-protector', '-mkernel',
           '-fapple-kext', '-Os', '-std=c++17', '-fno-exceptions', '-fno-rtti', '-fcheck-new',
           '-fno-c++-static-destructors', '-Wno-inconsistent-missing-override', '-c', src, '-o', obj]
    r = subprocess.run(cmd, capture_output=True, text=True)
    return r


def main():
    args = sys.argv[1:]
    model, slots = ensure('--regen' in args)
    C = model['classes']
    order = slots['order']
    BUILT = ['IOAccelerator', 'IOGraphicsAccelerator2', 'IOAccelEventMachine2', 'IOAccelEventMachineFast2', 'IOAccelTask', 'IOAccelDisplayMachine',
             'IOAccelMemory', 'IOAccelSysMemory', 'IOAccelMemoryMap', 'IOAccelVidMemory', 'IOAccelResource2', 'IOAccelSubmitter2',
             'IOAccelCommandQueue', 'IOAccelContext2', 'IOAccel2DContext2', 'IOAccelSharedUserClient2']
    if '--only' in args:
        only = args[args.index('--only') + 1].split(',')
        classes = [c for c in order if c in only]
    elif '--all' in args:
        classes = list(order)
    else:
        classes = [c for c in order if c in BUILT]   # the classes the leaf kext derives from (+ their bases); --all = every reconstructed class (informational: classes with unsupported SDK-range overrides mismatch)
    os.makedirs(BUILD, exist_ok=True)
    src, obj = os.path.join(BUILD, 'check_layout_test.cpp'), os.path.join(BUILD, 'check_layout_test.o')
    open(src, 'w').write(gen_tu(model, slots, classes))
    r = compile_tu(src, obj)
    if r.returncode:
        print('COMPILE FAILED (header or SDK mismatch); first errors:')
        print('\n'.join([l for l in r.stderr.splitlines() if 'error' in l][:15]))
        return 2
    # demangle cache
    dm = {}

    def dem(s):
        if s not in dm:
            dm[s] = demangle([s])[0]
        return dm[s]

    def strip_cls(s, cls):
        return s[len(cls) + 2:] if s.startswith(cls + '::') else None

    nchecked = 0
    nfwd = 0
    mism = []
    fwd = json.load(open(os.path.join(OUT, 'forwarded.json')))
    for c in classes:
        v = C[c]
        vt = objvt.vtable(obj, '__ZTV%d%s' % (len('N48T_' + c) + 0, 'N48T_' + c))
        tc = 'N48T_' + c
        if vt is None:
            mism.append((c, -1, 'no vtable emitted for ' + tc, ''))
            continue
        while vt and vt[-1]['kind'] == 'null':
            vt.pop()
        if len(vt) != v['nslots']:
            mism.append((c, -1, 'slot count: KC has %d, our subclass vtable has %d' % (v['nslots'], len(vt)), ''))
            continue
        sdk = next(b for b in v['chain'] if b in SDK_BASES)
        nsdk = C[sdk]['nslots']
        for i, e in enumerate(vt):
            row = v['rows'][i]
            nchecked += 1
            d = dem(e['sym']) if not e['sym'].startswith('<') else e['sym']
            if e['kind'] == 'def':
                own = strip_cls(d, tc)
                if row['pure']:
                    owner, ex = visible_decl(slots, c, i)
                    want = ('%s(%s)%s' % (ex['name'], ex['args'], ex['cv'])) if ex['kind'] == 'real' else '_vslot%d()' % i
                    if own != want:
                        mism.append((c, i, 'pure slot implemented under a different signature', 'expected %s::%s, got %s' % (tc, want, d)))
                    continue
                # allowed non-pure defs: what OSDefineMetaClassAndStructors adds (dtors, getMetaClass)
                base = C[sdk]['rows'][i]['name'] if i < nsdk else ''
                if own in ('~%s()' % tc, 'getMetaClass() const') and re.search(r'::(~\w+\(\)|getMetaClass\(\) const)$', base):
                    continue
                mism.append((c, i, 'unexpected override (KC slot is not pure)', 'our slot is %s, KC slot is %s' % (d, row['name'])))
                continue
            if e['kind'] != 'ref':
                mism.append((c, i, 'null slot inside vtable', ''))
                continue
            if row['pure']:
                mism.append((c, i, 'KC slot is pure virtual but our subclass did not override it', 'our slot is %s' % d))
                continue
            # EXACT rule (replaces the old declared-name comparison): an inherited slot must reference the very symbol the family's
            # own vtable of <Class> holds at that slot (any alias of that address), or the never-defined marker of a slot the family
            # does not export (the leaf class must then forward it: forwarded.json), so kxld/kmutil never has to patch anything.
            if e['sym'] in set(row['mangled']):
                if not exports.exported_name([e['sym']]):
                    mism.append((c, i, 'slot references a symbol the family/kernel does not export', e['sym']))
                continue
            if e['sym'].startswith('__n48_nonexported_') and e['sym'].endswith('_%d' % i):
                if i not in fwd.get(c, []):
                    mism.append((c, i, 'non-exported slot missing from forwarded.json', e['sym']))
                else:
                    nfwd += 1
                continue
            mism.append((c, i, 'inherited slot references the wrong symbol', 'ours %s ; family vtable of %s has %s' % (e['sym'], c, ' | '.join(row['mangled'])[:200])))
    # soft evidence: declared real names vs the family's OWN vtable target name for the introducing class
    agree = differ = 0
    for c in classes:
        for i_, e_ in slots['classes'][c]['slots'].items():
            if e_['kind'] == 'real' and e_['new'] and not C[c]['rows'][int(i_)]['pure']:
                own = C[c]['rows'][int(i_)]['name']
                if own == '%s::%s(%s)%s' % (c, e_['name'], e_['args'], e_['cv']):
                    agree += 1
                else:
                    differ += 1
    print('non-pure real-signature slots whose declared name equals the family class own vtable symbol: %d agree, %d differ (pure slots have no family name; their names come from the paravirt override)' % (agree, differ))
    # link audit: undefined symbols of the test object that no image exports. After the exact-name rule (gen_header.py labels every inherited slot with the
    # family's own exported symbol) the ONLY ones left are the __n48_nonexported_* markers of slots the family does not export; the leaf class must override
    # those with a forwarder (forwarded.json); verify the linked kext separately.
    ex = exports.load()
    und = [l.strip() for l in subprocess.run(['nm', '-u', obj], capture_output=True, text=True).stdout.splitlines() if l.strip()]
    missing = sorted(u for u in und if u not in ex)
    marker = [u for u in missing if u.startswith('__n48_nonexported_')]
    other = [u for u in missing if not u.startswith('__n48_nonexported_')]
    print('link audit: %d undefined symbols; %d are non-exported-slot markers (forwarded by the leaf class), %d others not exported by family/kernel; %d slots checked, %d of them forwarded' % (len(und), len(marker), len(other), nchecked, nfwd))
    for u in other[:8]:
        print('  NOT EXPORTED: ' + demangle([u])[0])
    if other:
        mism.append(('link audit', -1, 'undefined symbols that no image exports', ' '.join(other[:4])))
    print('classes checked: %d, slots compared: %d' % (len(classes), nchecked))
    if not mism:
        print('MATCH: every test subclass has the KC slot count and slot order (%d classes)' % len(classes))
        return 0
    print('MISMATCH: %d problem(s); first:' % len(mism))
    c, i, msg, extra = mism[0]
    print('  class %s slot %s: %s %s' % (c, i, msg, extra))
    for c, i, msg, extra in mism[1:12]:
        print('  also: class %s slot %s: %s %s' % (c, i, msg, extra))
    return 1


if __name__ == '__main__':
    sys.exit(main())
